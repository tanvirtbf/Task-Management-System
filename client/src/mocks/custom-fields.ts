export const customFieldsById = new Map(customFields.map((f) => [f.id, f]));

export const customFieldsByList = (listId: string): CustomField[] =>
  customFields
    .filter((f) => f.scopeType === "list" && f.scopeId === listId)
    .sort((a, b) => a.position - b.position);

export const customFieldsByScope = (
  scopeType: "workspace" | "space" | "list",
  scopeId?: string,
): CustomField[] =>
  customFields
    .filter(
      (f) => f.scopeType === scopeType && (!scopeId || f.scopeId === scopeId),
    )
    .sort((a, b) => a.position - b.position);
